#!/usr/bin/env node
'use strict';
// Builds a single-file Windows executable (cb.exe) containing the server and the CLI, using Node's
// single-executable-application feature, and packages it with the extension and setup scripts into
// dist/chromium-bridge-win-x64.zip. Only needed by whoever publishes a release; users of the source don't run this.
//
//   node build-exe.js
//
// Needs: Windows, Node 20+ (the node.exe that runs this is the one embedded), network access for `npx postject`.
// Usage of the result:   cb.exe server    starts the server;   cb.exe <command>   is the CLI (same as `node cb.js`).

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const root = __dirname;
const dist = path.join(root, 'dist');
const stage = path.join(dist, 'chromium-bridge-win-x64');
const read = f => fs.readFileSync(path.join(root, f), 'utf8').replace(/^#!.*\n/, '');
const sh = (cmd, args, opts) => execFileSync(cmd, args, { stdio: 'inherit', shell: process.platform === 'win32' && cmd === 'npx', ...opts });

fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(stage, { recursive: true });

// 1. One script: `cb.exe server` runs server.js, anything else runs cb.js.
const bundle = `'use strict';
// Generated by build-exe.js from server.js and cb.js. Do not edit.
const args = process.argv.slice(process.argv[1] === process.execPath ? 2 : 1);
if (args[0] === 'server') {
  process.argv = [process.argv[0], 'server', ...args.slice(1)];
  (function () {
${read('server.js')}
  })();
} else {
  process.argv = [process.argv[0], 'cb', ...args];
  (function () {
${read('cb.js')}
  })();
}
`;
fs.writeFileSync(path.join(dist, 'bundle.js'), bundle);
fs.writeFileSync(path.join(dist, 'sea-config.json'), JSON.stringify({
  main: path.join(dist, 'bundle.js'), output: path.join(dist, 'sea.blob'), disableExperimentalSEAWarning: true,
}));

// 2. Blob, then inject it into a copy of node.exe.
sh(process.execPath, ['--experimental-sea-config', path.join(dist, 'sea-config.json')]);
const exe = path.join(stage, 'cb.exe');
fs.copyFileSync(process.execPath, exe);
sh('npx', ['--yes', 'postject', `"${exe}"`, 'NODE_SEA_BLOB', `"${path.join(dist, 'sea.blob')}"`,
  '--sentinel-fuse', 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2']);

// 3. Package: exe + extension (without the generated config.js) + setup scripts + docs.
fs.mkdirSync(path.join(stage, 'extension'));
for (const f of fs.readdirSync(path.join(root, 'extension'))) {
  if (f !== 'config.js') fs.copyFileSync(path.join(root, 'extension', f), path.join(stage, 'extension', f));
}
for (const f of ['setup.bat', 'setup.ps1', 'start-bridge.ps1', 'install-autostart.ps1', 'uninstall-autostart.ps1', 'README.md', 'LICENSE']) {
  fs.copyFileSync(path.join(root, f), path.join(stage, f));
}
const zip = path.join(dist, 'chromium-bridge-win-x64.zip');
execFileSync('powershell', ['-NoProfile', '-Command', `Compress-Archive -Path '${stage}\\*' -DestinationPath '${zip}' -Force`], { stdio: 'inherit' });
console.log(`\nBuilt ${zip} (${(fs.statSync(zip).size / 1048576).toFixed(1)} MB)`);
