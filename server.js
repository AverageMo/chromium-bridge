#!/usr/bin/env node
'use strict';
// Chromium Bridge server. Zero dependencies.
//   extension  --long-poll GET /poll, POST /result-->  server  <--POST /cmd--  cb.js / curl
// Listens on 127.0.0.1 only. Every endpoint needs the bearer token in token.txt.

const http = require('http');
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

// Where token.txt and extension/ live: next to the .exe when packaged, otherwise next to this file.
const APPDIR = (() => { try { if (require('node:sea').isSea()) return path.dirname(process.execPath); } catch { /* not a single-executable build */ } return __dirname; })();

const HOST = '127.0.0.1';
const PORT = Number(process.env.CB_PORT) || 9333;
const POLL_HOLD_MS = 20000;
const CONNECTED_WINDOW_MS = 45000;
const DEFAULT_TIMEOUT_MS = 60000;
const MAX_BODY = 64 * 1024 * 1024;

const tokenFile = path.join(APPDIR, 'token.txt');
let token;
try { token = fs.readFileSync(tokenFile, 'utf8').trim(); } catch { /* first run */ }
if (!token) {
  token = crypto.randomBytes(24).toString('hex');
  fs.writeFileSync(tokenFile, token + '\n', { mode: 0o600 });
}

// Hand the token to the unpacked extension so no copy/paste is needed (same machine, same trust as token.txt).
try {
  fs.writeFileSync(path.join(APPDIR, 'extension', 'config.js'),
    `// generated by server.js — do not edit or commit\nself.CB_DEFAULTS = ${JSON.stringify({ port: PORT, token })};\n`);
} catch (e) { console.error('could not write extension/config.js:', e.message); }

const queue = [];          // commands waiting for the extension
const inflight = new Map(); // id -> {resolve, timer}
let poller = null;          // held /poll response
let pollerTimer = null;
let lastPollAt = 0;
let seq = 0;

const connected = () => Date.now() - lastPollAt < CONNECTED_WINDOW_MS;

function safeEq(a, b) {
  const x = Buffer.from(a), y = Buffer.from(b);
  return x.length === y.length && crypto.timingSafeEqual(x, y);
}

function send(res, code, obj) {
  const body = obj === undefined ? '' : JSON.stringify(obj);
  res.writeHead(code, { 'Content-Type': 'application/json', 'Cache-Control': 'no-store' });
  res.end(body);
}

function readBody(req) {
  return new Promise((resolve, reject) => {
    const chunks = [];
    let size = 0;
    req.on('data', c => {
      size += c.length;
      if (size > MAX_BODY) { reject(new Error('body too large')); req.destroy(); return; }
      chunks.push(c);
    });
    req.on('end', () => {
      try { resolve(chunks.length ? JSON.parse(Buffer.concat(chunks).toString('utf8')) : {}); }
      catch (e) { reject(new Error('invalid JSON')); }
    });
    req.on('error', reject);
  });
}

function releasePoller(cmd) {
  if (!poller) return false;
  clearTimeout(pollerTimer);
  const res = poller;
  poller = null;
  if (cmd) send(res, 200, cmd); else send(res, 204);
  return true;
}

function flush() {
  if (poller && queue.length) {
    const c = queue.shift();
    releasePoller({ id: c.id, method: c.method, params: c.params });
  }
}

const server = http.createServer(async (req, res) => {
  try {
    // DNS-rebinding guard: only accept requests addressed to loopback.
    const host = (req.headers.host || '').replace(/:\d+$/, '');
    if (host !== '127.0.0.1' && host !== 'localhost') return send(res, 403, { error: 'bad host' });
    // Block web pages (CSRF). Extensions and CLI clients are allowed through to the token check.
    const origin = req.headers.origin;
    if (origin && !origin.startsWith('chrome-extension://')) return send(res, 403, { error: 'bad origin' });

    const auth = req.headers.authorization || '';
    if (!auth.startsWith('Bearer ') || !safeEq(auth.slice(7), token)) return send(res, 401, { error: 'unauthorized' });

    const url = new URL(req.url, `http://${HOST}`);

    if (req.method === 'GET' && url.pathname === '/status') {
      return send(res, 200, { connected: connected(), queued: queue.length, inflight: inflight.size, lastPollAgoMs: lastPollAt ? Date.now() - lastPollAt : null });
    }

    if (req.method === 'GET' && url.pathname === '/poll') {
      lastPollAt = Date.now();
      releasePoller(null); // a newer poll replaces a stale one
      poller = res;
      req.on('close', () => { if (poller === res) { clearTimeout(pollerTimer); poller = null; } });
      pollerTimer = setTimeout(() => { lastPollAt = Date.now(); releasePoller(null); }, POLL_HOLD_MS);
      flush();
      return;
    }

    if (req.method === 'POST' && url.pathname === '/result') {
      const body = await readBody(req);
      const p = inflight.get(body.id);
      if (p) {
        clearTimeout(p.timer);
        inflight.delete(body.id);
        p.resolve(body.error ? { ok: false, error: body.error } : { ok: true, result: body.result });
      }
      return send(res, 200, { ok: true });
    }

    if (req.method === 'POST' && url.pathname === '/cmd') {
      const body = await readBody(req);
      if (!body.method || typeof body.method !== 'string') return send(res, 400, { ok: false, error: 'method required' });
      if (!connected()) return send(res, 503, { ok: false, error: 'extension not connected (is it installed, enabled, and given the token?)' });
      const id = ++seq;
      const timeoutMs = Math.min(Number(body.timeout) || DEFAULT_TIMEOUT_MS, 10 * 60 * 1000);
      const result = await new Promise(resolve => {
        const timer = setTimeout(() => {
          inflight.delete(id);
          resolve({ ok: false, error: `timed out after ${timeoutMs} ms` });
        }, timeoutMs);
        inflight.set(id, { resolve, timer });
        queue.push({ id, method: body.method, params: body.params || {} });
        flush();
      });
      return send(res, result.ok ? 200 : 500, result);
    }

    send(res, 404, { error: 'not found' });
  } catch (e) {
    if (!res.headersSent) send(res, 400, { error: String(e.message || e) });
  }
});

server.listen(PORT, HOST, () => {
  console.log(`Chromium Bridge listening on http://${HOST}:${PORT}`);
  console.log(`Token file: ${tokenFile}`);
});
server.on('error', e => { console.error('server error:', e.message); process.exit(1); });
